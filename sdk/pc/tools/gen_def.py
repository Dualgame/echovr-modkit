#!/usr/bin/env python3
"""gen_def.py - generate winmm.def for the echovr-modloader proxy, and verify a built DLL.

  gen_def.py gen   [--sys PATH] [--out src/winmm.def]   module-definition file for the proxy
  gen_def.py check [--sys PATH] BUILT_DLL               compare BUILT_DLL's export table with the system one

Design (see ../README.md "How it forwards"):
  * The proxy is itself named winmm.dll and sits in the app dir, so a bare `winmm.<fn>` forwarder would
    name THIS module (app dir wins the search) and loop. Full-path PE forwarders are rejected by the MSVC
    linker (it reads the path as an internal symbol). So the proxy forwards to a renamed copy, winmm_orig.
  * WRAP = the winmm functions any module in the echovr.exe process imports (echovr.exe: timeBeginPeriod,
    timeEndPeriod, timeGetDevCaps, timeGetTime; OculusSpatializerWwise.dll adds timeGetSystemTime,
    timeKillEvent, timeSetEvent - verified on PC 6323983201049540). These are exported as REAL C
    wrappers (winmm_proxy.c) that lazy-resolve the system winmm by its absolute System32 path on first
    call - after DllMain, never under the loader lock. So Echo VR itself needs NO winmm_orig.dll.
  * Every other export is emitted as a forwarder to winmm_orig, present ONLY so the proxy's export table is
    identical to the system one (count + ordinals + names). Nothing in this process imports them, so the
    loader never snaps them. gen also writes winmm_orig.def: build.cmd makes an import lib from it so those
    forwarders resolve at link time (a same-name forwarder to a module with no import lib is unresolved).

Read-only apart from --out. Run with:  python3 -I tools/gen_def.py gen
"""
import argparse
from pathlib import Path

import pefile

SYS_DEFAULT = "/mnt/c/Windows/System32/winmm.dll"
# NT path to the system copy; forwarder targets for the never-snapped exports only.
FWD_TARGET = "winmm_orig"  # a renamed copy of the system winmm; only consulted if a module imports one of the 173 parity exports (echovr.exe + its DLLs do not). See ../README.md.
# Functions some module in the process imports -> implemented as real wrappers in winmm_proxy.c.
WRAP = ["timeBeginPeriod", "timeEndPeriod", "timeGetDevCaps", "timeGetTime",
        "timeGetSystemTime", "timeKillEvent", "timeSetEvent"]


def read_exports(path):
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories(
        directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    d = pe.DIRECTORY_ENTRY_EXPORT
    return d, sorted(d.symbols, key=lambda s: s.ordinal)


def synth(ordinal):
    """A synthetic name for a system export that has only an ordinal."""
    return "_winmm_ord%d" % ordinal


def cmd_gen(a):
    d, syms = read_exports(a.sys)
    sysnames = {s.name.decode() for s in syms if s.name}
    for w in WRAP:
        if w not in sysnames:
            raise SystemExit("WRAP name %r not in system winmm - fix WRAP" % w)
    out = ["; GENERATED by tools/gen_def.py from %s - do not edit." % Path(a.sys).name,
           "; %d exports, base ordinal %d. WRAP = real wrappers; rest = parity forwarders to %s."
           % (len(syms), d.struct.Base, FWD_TARGET),
           "LIBRARY winmm", "EXPORTS"]
    # Import-library source for the fake FWD_TARGET module, so the forwarders resolve at link time.
    orig = ["; GENERATED by tools/gen_def.py - import-lib source for the forwarder target.",
            "LIBRARY %s" % FWD_TARGET, "EXPORTS"]
    nwrap = nfwd = nnoname = 0
    for s in syms:
        nm = s.name.decode() if s.name else synth(s.ordinal)
        noname = "" if s.name else " NONAME"
        if s.name and nm in WRAP:
            out.append("    %s @%d" % (nm, s.ordinal))              # our real wrapper
            nwrap += 1
        else:
            out.append("    %s=%s.%s @%d%s" % (nm, FWD_TARGET, nm, s.ordinal, noname))
            orig.append("    %s @%d%s" % (nm, s.ordinal, noname))   # the target module "exports" it
            if s.name:
                nfwd += 1
            else:
                nnoname += 1
    Path(a.out).write_text("\n".join(out) + "\n")
    orig_out = Path(a.out).with_name(FWD_TARGET + ".def")
    orig_out.write_text("\n".join(orig) + "\n")
    print("wrote %s: %d exports (%d wrappers, %d forwarders, %d ordinal-only), base %d"
          % (a.out, nwrap + nfwd + nnoname, nwrap, nfwd, nnoname, d.struct.Base))
    print("wrote %s: %d entries (import-lib source for %s)" % (orig_out, nfwd + nnoname, FWD_TARGET))


def cmd_check(a):
    _, sysd = read_exports(a.sys)
    _, built = read_exports(a.built)
    sysset = {(s.ordinal, s.name.decode() if s.name else None) for s in sysd}
    bset = {(s.ordinal, s.name.decode() if s.name else None) for s in built}
    missing = sorted(sysset - bset)
    extra = sorted(bset - sysset)
    realfns = sorted(s.name.decode() for s in built if s.name and not s.forwarder)
    print("system winmm: %d exports" % len(sysd))
    print("built  dll  : %d exports" % len(built))
    print("missing (system not in built):", missing)
    print("extra   (built not in system):", extra)
    print("real (non-forwarder) exports in built:", realfns)
    ok = (not missing and not extra and set(realfns) == set(WRAP))
    print("RESULT:", "OK" if ok else "MISMATCH (real set vs WRAP: %s)" % (set(realfns) ^ set(WRAP)))
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--sys", default=SYS_DEFAULT)
    g.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "src" / "winmm.def"))
    g.set_defaults(fn=cmd_gen)
    c = sub.add_parser("check")
    c.add_argument("--sys", default=SYS_DEFAULT)
    c.add_argument("built")
    c.set_defaults(fn=cmd_check)
    a = ap.parse_args()
    raise SystemExit(a.fn(a) or 0)


if __name__ == "__main__":
    main()
